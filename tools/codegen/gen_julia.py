"""Generate completion-friendly Julia wrappers from the FSDA intermediate representation."""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path


_ROUTINES_RE = re.compile(
    r"const\s+FSDA_ROUTINES\s*=\s*\[(?P<body>.*?)\]",
    re.DOTALL,
)
_ROUTINE_RE = re.compile(r":([A-Za-z_]\w*)")
_IDENTIFIER_RE = re.compile(r"^[A-Za-z_]\w*$")


def _read_routines(source: Path) -> list[str]:
    match = _ROUTINES_RE.search(source.read_text(encoding="utf-8"))
    if match is None:
        raise ValueError(f"FSDA_ROUTINES was not found in {source}")
    return _ROUTINE_RE.findall(match.group("body"))


def _julia_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def _format_type(type_spec) -> str:
    if not type_spec:
        return "MATLAB value"
    atoms = [" + ".join(str(atom) for atom in branch) for branch in type_spec]
    return " or ".join(atoms)


def _format_doc(record: dict) -> str:
    required = [
        item["name"]
        for item in record.get("inputs", [])
        if item.get("kind") == "required"
    ]
    keywords = [
        item["name"]
        for item in record.get("inputs", [])
        if item.get("kind") == "namevalue"
    ]
    signature = ", ".join(required)
    if keywords:
        signature += ("; " if signature else "; ") + ", ".join(keywords)
    lines = [f"    {record['name']}({signature})"]
    lines.append("")
    description = record.get("description_short") or ""
    if description:
        lines.append(str(description))
    long_description = record.get("description_long") or ""
    if long_description and long_description != description:
        lines.extend(["", str(long_description)])
    if required:
        lines.extend(["", "# Arguments"])
        for item in record["inputs"]:
            if item.get("kind") == "required":
                lines.append(
                    f"- `{item['name']}`: {_format_type(item.get('matlab_type'))}. "
                    f"{item.get('purpose_short') or ''}"
                )
    if keywords:
        lines.extend(["", "# Keywords"])
        for item in record["inputs"]:
            if item.get("kind") == "namevalue":
                default = item.get("default")
                default_text = "" if default is None else f" Default: `{default}`."
                lines.append(
                    f"- `{item['name']}`: {_format_type(item.get('matlab_type'))}. "
                    f"{item.get('purpose_short') or ''}{default_text}"
                )
    url = record.get("fsda_url")
    if url:
        lines.extend(["", f"Documentation: {url}"])
    return '"""\n' + "\n".join(lines) + '\n"""'


def _generate_record(record: dict) -> str:
    name = record["name"]
    inputs = record.get("inputs", [])
    required = [item for item in inputs if item.get("kind") == "required"]
    keywords = [item for item in inputs if item.get("kind") == "namevalue"]
    unsupported = [
        item for item in inputs if item.get("kind") not in {"required", "namevalue"}
    ]
    if unsupported:
        names = ", ".join(item["name"] for item in unsupported)
        raise ValueError(f"{name}: unsupported input kinds for {names}")
    for item in inputs:
        if not _IDENTIFIER_RE.fullmatch(item["name"]):
            raise ValueError(f"{name}: invalid Julia input name {item['name']!r}")

    positional = ", ".join(item["name"] for item in required)
    keyword_text = ", ".join(f"{item['name']}=_UNSET" for item in keywords)
    signature = positional
    if keyword_text:
        signature += "; " + keyword_text
        signature += ", "
    else:
        signature += "; "
    signature += "nargout=1, echo_output=false, options=nothing"

    nv = ", ".join(f"{item['name']}={item['name']}" for item in keywords)
    call_args = ", ".join(item["name"] for item in required)
    body = [
        _format_doc(record),
        f"function {name}({signature})",
        f"    nv = _set_only((; {nv}))" if nv else "    nv = NamedTuple()",
        f"    return call(_engine(), {_julia_string(name)}"
        f"{', ' + call_args if call_args else ''}; "
        "nargout=nargout, echo_output=echo_output, options=options, nv...)",
        "end",
        f"export {name}",
    ]
    return "\n".join(body)


def generate(ir_path: Path, facade_path: Path, output_path: Path) -> list[str]:
    records = json.loads(ir_path.read_text(encoding="utf-8"))
    by_name = {record["name"]: record for record in records}
    routines = _read_routines(facade_path)
    generated = [name for name in routines if name in by_name]

    blocks = [
        "# This file is generated by tools/codegen/gen_julia.py.",
        "# Do not edit manually; regenerate from the supplied IR JSON file.",
        "",
        "const _GENERATED_ROUTINES = Set{Symbol}([" +
        ", ".join(f":{name}" for name in generated) +
        "])",
        "",
    ]
    blocks.extend(_generate_record(by_name[name]) for name in generated)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n\n".join(blocks) + "\n", encoding="utf-8")
    return generated


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--ir",
        type=Path,
        required=True,
        help="Path to the FSDA intermediate representation JSON file",
    )
    parser.add_argument(
        "--facade",
        type=Path,
        default=Path("packages/FSDAjl/src/FSDABridge.jl"),
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("packages/FSDAjl/src/generated/routines.jl"),
    )
    args = parser.parse_args()
    generated = generate(args.ir, args.facade, args.output)
    print(f"generated {len(generated)} routines: {', '.join(generated)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
